/** Dutch fallback for form suffixes, which PokéAPI does not localize. */
export function translateDutchFormSuffix(suffix: string): string {
  return suffix
    .split("-")
    .map((word) => {
      const translated = DUTCH_FORM_WORDS[word];
      return translated ?? word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(" ");
}